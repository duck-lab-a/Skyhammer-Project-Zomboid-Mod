-- One whole sortie at the defaults: one strike, the ten jets going over 0.4 s apart, each pair of
-- bombs walking the carpet down the line after its jet
column()
onStation()
check(S.Phase("f22") == "ON_STATION", "on station after its arrival (" .. tostring(S.Phase("f22")) .. ")")
check(S.Ammo("raid") == 1, "one strike by default")
check(S.Supports.f22.markKind() == "raid", "the terminal's mark row")
SAID = {}; SOUNDS = {}
local ok = mark(140, 100)
check(ok == true, "mark opened")
check(SAID[1] == "F22Mark" and SAID[2] == "F22RollIn", "mark prompt, then the roll-in (" .. table.concat(SAID, ",") .. ")")
check(S.IsAiming() == false, "mark closed")
check(S.Ammo("raid") == 0, "the strike is spent")
local run1 = S.Store().f22VisualRun
check(run1 ~= nil and run1.len == 70 and run1.raid == 1, "visual record")
check(run1 and deg(run1.heading) == 90, "along the column, away from the player (" .. (run1 and deg(run1.heading) or "-") .. ")")
check(run1 and near(run1.x, 140.5) and near(run1.y, 100.5 - 35), "the line starts 35 tiles before the mark")
check(inflight() == 20, "twenty bombs in the air at once (" .. inflight() .. ")")
local track = S.F22Track()
check(track ~= nil and track[5] == 40 and track[6] == 14, "the sensor map shows the line, the strip and its reach")
check(S.AimKinds.raid.width == 40 and S.AimKinds.raid.edge == 14 and S.AimKinds.raid.preview ~= nil,
    "the mark on the map shows the strip round the line")
check(S.F22Running() == true, "running")
check(S.Supports.f22.phaseText("ON_STATION") == "IGUI_SH_Phase_F22Run", "terminal phase text while it runs")
check(S.Supports.f22.hint("ON_STATION") == "IGUI_SH_Hint_F22Last", "terminal hint: the last strike is under way")
-- (the player 34.5 tiles along the line's track from its start: each jet nearest them 6.10 s plus
-- 0.4 s a jet, its roar started 2.0 s before: 4.1, 4.5, 4.9, 5.3, ...)
run(5000)
check(count(SOUNDS, "SH_F22_Flyby") == 1 and count(SOUNDS, "SH_F22_Flyby2") == 1 and count(SOUNDS, "SH_F22_Flyby3") == 1
    and count(SOUNDS, "SH_A10_Flyby") == 0, "the first three jets' roars by 5.0 s, each its own recording speed")
check(not said("F22Release"), "no bombs away before 5.2 s")
run(400)
check(said("F22Release"), "bombs away on the radio by 5.4 s")
check(count(SOUNDS, "SH_F22_Flyby") == 2, "the fourth jet's roar (5.3 s)")
check(count(SOUNDS, "SH_F22_Boom") == 0, "no sonic boom before the lead passes")
run(800)
check(count(SOUNDS, "SH_F22_Boom") == 1, "one sonic boom as the lead passes nearest the player (6.10 s)")
check(count(SOUNDS, "SH_F22_Flyby3") == 2, "the sixth jet's roar (6.10 s)")
check(alive() == 11, "nothing down before the first bomb lands at 6.9 s (" .. alive() .. ")")
run(900)
check(inflight() == 18, "the lead's two bombs down by 7.1 s, the rest still falling (" .. inflight() .. ")")
check(alive() < 11 and alive() > 0, "the lead's two took the line's start only (" .. alive() .. " up)")
check(count(SOUNDS, "SH_F22_Boom") == 3, "a boom a jet, 0.4 s apart (" .. count(SOUNDS, "SH_F22_Boom") .. " by 7.1 s)")
check(count(SOUNDS, "SH_Bomb_Impact") == 2, "the lead's two both heard (" .. count(SOUNDS, "SH_Bomb_Impact") .. ")")
run(400)
check(inflight() == 16, "the second jet's two down 0.4 s later (" .. inflight() .. ")")
check(count(SOUNDS, "SH_F22_Boom") == 4, "four booms by 7.5 s (" .. count(SOUNDS, "SH_F22_Boom") .. ")")
run(3300)
check(alive() == 0, "the whole column under the line is down by 10.8 s (" .. alive() .. ")")
check(inflight() == 0, "every bomb has landed")
check(S.F22Track() == nil, "the map line is gone once they are down")
check(count(SOUNDS, "SH_F22_Boom") == 10, "ten sonic booms, one a jet (" .. count(SOUNDS, "SH_F22_Boom") .. ")")
check(count(SOUNDS, "SH_F22_Flyby") == 4 and count(SOUNDS, "SH_F22_Flyby2") == 3 and count(SOUNDS, "SH_F22_Flyby3") == 3,
    "ten roars, the three recordings in turn")
check(count(SOUNDS, "SH_Incoming") == 3, "three bombs heard falling (" .. count(SOUNDS, "SH_Incoming") .. ")")
check(count(SOUNDS, "SH_Bomb_Impact") == 20, "every bomb its blast sound, two a jet (" .. count(SOUNDS, "SH_Bomb_Impact") .. ")")
check(not said("F22Winchester"), "no winchester before 12.0 s")
run(1500)
check(said("F22Winchester"), "winchester after the last strike")
check(S.Phase("f22") == "REARM", "home after its strike (" .. tostring(S.Phase("f22")) .. ")")
check(S.F22Running() == false, "not running")
done("strike")
